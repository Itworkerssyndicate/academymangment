  /* ============================================================
     3. CORE — GET ICON
     ============================================================ */

  function get(name, options) {
    if (!name || !ICON_PATHS[name]) {
      log('debug', 'Icon not found: ' + name);
      return '';
    }

    options = options || {};

    var size = options.size != null ? options.size : 24;
    var strokeWidth = options.strokeWidth != null ? options.strokeWidth : 2;
    var color = options.color ? ' style="color:' + escapeHtml(options.color) + '"' : '';
    var className = options.className ? ' ' + escapeHtml(options.className) : '';
    var ariaHidden = options.ariaHidden !== false ? ' aria-hidden="true"' : '';
    var ariaLabel = options.ariaLabel ? ' aria-label="' + escapeHtml(options.ariaLabel) + '"' : '';

    var strokeAttr = '';
    // Some icons are filled (social) — don't set stroke
    var isFilled = (
      name === 'facebook' ||
      name === 'twitter' ||
      name === 'linkedin' ||
      name === 'youtube' ||
      name === 'whatsapp' ||
      name === 'star-filled'
    );

    if (!isFilled) {
      strokeAttr = ' fill="none" stroke="currentColor" stroke-width="' + strokeWidth +
                   '" stroke-linecap="round" stroke-linejoin="round"';
    }

    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" ' +
           'width="' + size + '" height="' + size + '"' +
           strokeAttr +
           color +
           ' class="itws-icon itws-icon-' + escapeHtml(name) + className + '"' +
           ariaHidden +
           ariaLabel +
           '>' + ICON_PATHS[name] + '</svg>';
  }

  /* ============================================================
     4. CORE — INJECT
     ============================================================ */

  function inject(el, name, options) {
    if (!el) return false;
    var svg = get(name, options);
    if (!svg) return false;
    el.innerHTML = svg;
    el.setAttribute('data-icon-rendered', 'true');
    return true;
  }

  function set(el, name, options) {
    return inject(el, name, options);
  }

  function remove(el) {
    if (!el) return false;
    el.innerHTML = '';
    el.removeAttribute('data-icon-rendered');
    return true;
  }

  /* ============================================================
     5. AUTO-REPLACE [data-icon]
     ============================================================ */

  function replace(root) {
    root = root || document;
    if (!root || typeof root.querySelectorAll !== 'function') return;

    var els = root.querySelectorAll('[data-icon]:not([data-icon-rendered])');
    for (var i = 0; i < els.length; i++) {
      var el = els[i];
      var name = el.getAttribute('data-icon');
      if (!name) continue;

      var sizeAttr = el.getAttribute('data-icon-size');
      var strokeAttr = el.getAttribute('data-icon-stroke');
      var colorAttr = el.getAttribute('data-icon-color');
      var labelAttr = el.getAttribute('data-icon-label');

      var options = {};
      if (sizeAttr) options.size = parseInt(sizeAttr, 10);
      if (strokeAttr) options.strokeWidth = parseFloat(strokeAttr);
      if (colorAttr) options.color = colorAttr;
      if (labelAttr) options.ariaLabel = labelAttr;

      inject(el, name, options);
    }
  }

  /* ============================================================
     6. EXISTS / NAMES
     ============================================================ */

  function exists(name) {
    return !!name && !!ICON_PATHS[name];
  }

  function names() {
    return Object.keys(ICON_PATHS);
  }

  function count() {
    return Object.keys(ICON_PATHS).length;
  }

  /* ============================================================
     7. EXPORT
     ============================================================ */

  window.Icons = {
    _initialized: true,

    // Core
    get: get,
    inject: inject,
    set: set,
    remove: remove,
    replace: replace,

    // Info
    exists: exists,
    names: names,
    count: count,

    // Raw paths (advanced use)
    paths: ICON_PATHS
  };

  // Shorthand globals
  window.getIcon = get;
  window.renderIcon = inject;

  /* ============================================================
     8. AUTO-RUN ON LOAD
     ============================================================ */

  function autoRun() {
    try {
      replace(document);
    } catch (e) {
      log('error', 'Auto-run failed', e);
    }

    // MutationObserver for dynamically added icons
    try {
      if (typeof MutationObserver !== 'undefined') {
        var observer = new MutationObserver(function (mutations) {
          var needsReplace = false;
          for (var i = 0; i < mutations.length; i++) {
            var m = mutations[i];
            if (m.type === 'childList' && m.addedNodes.length > 0) {
              needsReplace = true;
              break;
            }
            if (m.type === 'attributes' && m.attributeName === 'data-icon') {
              needsReplace = true;
              break;
            }
          }
          if (needsReplace) {
            // Debounce via microtask
            setTimeout(function () {
              replace(document);
            }, 0);
          }
        });

        observer.observe(document.body || document.documentElement, {
          childList: true,
          subtree: true,
          attributes: true,
          attributeFilter: ['data-icon']
        });
      }
    } catch (e) {
      log('error', 'MutationObserver failed', e);
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', autoRun);
  } else {
    autoRun();
  }

